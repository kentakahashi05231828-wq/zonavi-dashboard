/**
 * 東京造形大学の学生数（在籍者数）。
 *
 * このアプリは学内専用なので「分母が確定している」のが最大の強みです。
 * 277 台という数字は単体では良し悪しが判断できませんが、
 * 学生数で割れば「学内浸透率」になり、卒制の見出しに置ける数字になります。
 *
 * 分母が有限だと戦略も変わります。ある時点から新規獲得は頭打ちになるので、
 * そこから先の伸びしろは継続率だけになります。
 *
 * 大学公式の在籍者数（学部＋大学院）に置き換えてください。
 * null のままだと浸透率は表示されません。
 */
export const STUDENT_COUNT = null;   // 例: 1800

/**
 * 学年暦。
 *
 * 大学アプリの利用は、ほぼ学事暦で説明がつきます。
 * これを重ねずに「9月に落ちた」と書いても意味がなく、
 * 「夏季休業だから落ちた、授業再開で戻った」と書けて初めて分析になります。
 *
 * 「日別の推移」のグラフに重ねて表示し、レポートの文章にも反映します。
 *
 *   { from: "2026-08-05", to: "2026-09-20", label: "夏季休業", kind: "break" }
 *   { on:   "2026-09-21",                   label: "後期授業開始", kind: "milestone" }
 *
 * kind は break（期間・薄い帯）／ milestone（1日・縦線）／ event（1日・縦線、色違い）。
 * 大学公式の学年暦を見ながら足してください。日付は JST の yyyy-MM-dd です。
 */
export const ACADEMIC_CALENDAR = [
  // ▼ ここに実際の学年暦を入れてください（以下は書き方の例。コメントのままでは表示されません）
  // { from: "2026-08-05", to: "2026-09-20", label: "夏季休業",     kind: "break" },
  // { on:   "2026-09-21",                   label: "後期授業開始", kind: "milestone" },
  // { from: "2026-09-21", to: "2026-09-30", label: "履修登録",     kind: "break" },
  // { from: "2027-01-26", to: "2027-02-05", label: "定期試験",     kind: "break" },
  // { on:   "2026-10-24",                   label: "ZOKEI展",     kind: "event" },
];

/** 期間として扱える形になっているか */
export const calendarEntries = () =>
  ACADEMIC_CALENDAR
    .map(e => ({ ...e, from: e.from ?? e.on, to: e.to ?? e.on }))
    .filter(e => /^\d{4}-\d{2}-\d{2}$/.test(e.from) && /^\d{4}-\d{2}-\d{2}$/.test(e.to))
    .sort((a, b) => a.from.localeCompare(b.from));
